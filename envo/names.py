# Окончания фамилий. Сильные почти не встречаются у имён, слабые бывают и там, и там.
STRONG = ("ов", "ев", "ёв", "ский", "цкий", "ская", "цкая", "ых", "их", "енко", "швили", "дзе",
          "ова", "ева", "ёва", "оглы")
WEAK = ("ин", "ын", "ина", "ына", "ян", "чук", "юк", "ук", "ко")

MONTHS = {1: "января", 2: "февраля", 3: "марта", 4: "апреля", 5: "мая", 6: "июня", 7: "июля",
          8: "августа", 9: "сентября", 10: "октября", 11: "ноября", 12: "декабря"}


def _surname_score(token: str) -> int:
    low = token.lower()
    if low in GIVEN:
        return 0
    if low.endswith(STRONG) and len(low) >= 4:
        return 2
    if low.endswith(WEAK) and len(low) >= 5:
        return 1
    return 0


def _title(token: str) -> str:
    return "".join(p if p == "-" else p.capitalize() for p in re.split(r"([-])", token.lower()))


def first_name(full: str | None) -> str:
    """Имя из полного ФИО. Пустая строка, если уверенности нет."""
    if not full:
        return ""
    tokens = [t for t in re.split(r"[\s,]+", str(full).strip()) if re.search(r"[A-Za-zА-Яа-яЁё]", t)]
    if not tokens:
        return ""
    if len(tokens) == 1:
        # Латиница одним словом — скорее логин, чем имя.
        return "" if re.fullmatch(r"[A-Za-z'-]+", tokens[0]) else _title(tokens[0])
    for token in tokens:
        if token.lower() in GIVEN:
            return _title(token)
    if any(re.fullmatch(r"[A-Za-z'-]+", t) for t in tokens):
        return ""
    first, second = _surname_score(tokens[0]), _surname_score(tokens[1])
    if first > second:
        return _title(tokens[1])
    if first == 0 and second > 0:
        return _title(tokens[0])
    return ""


def plural(n: int, one: str, few: str, many: str) -> str:
    """Склонение существительного при числительном."""
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many


def tickets_phrase(count: int) -> str:
    """«билет», «2 билета», «5 билетов»."""
    word = plural(count, "билет", "билета", "билетов")
    return word if count == 1 else f"{count} {word}"
